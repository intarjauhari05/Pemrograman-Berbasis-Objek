# 4) Import fungsi cos dan tan
from math import cos, tan

print("\n--- Langkah 4: cos(pi / 2) dan tan(pi / 4) ---")
print("cos(pi / 2):", cos(pi / 2))
print("tan(pi / 4):", tan(pi / 4))
